function buildKnowledgeContext(userMessage) {
  const text = String(userMessage || "").toLowerCase();
  const wantsSiteHelp =
    /(сайт|страниц|куда нажать|как оформить|как заказать|как оплат|как войти|где|профил|заказ)/i.test(text);
  const wantsPrintHelp =
    /(3d|3-д|печат|sla|sls|fdm|pla|abs|petg|смол|материал|слой|толщин|прочност|детализац|моделирован|сканирован|оцифров|черт[её]ж|эскиз)/i.test(text);

  const blocks = [];
  if (wantsSiteHelp) {
    blocks.push(`Структура сайта:\n${SITE_MAP}`);
    blocks.push(`Подсказки по навигации:\n${SITE_GUIDE}`);
    blocks.push(`Сценарий заказа:\n${ORDER_FLOW}`);
    blocks.push(`Сценарии услуг:\n${SERVICE_SCENARIOS}`);
  }
  if (wantsPrintHelp) {
    blocks.push(`Знания по 3Д-печати:\n${PRINT_BASICS}`);
    blocks.push(`Сценарии услуг:\n${SERVICE_SCENARIOS}`);
  }
  if (blocks.length === 0) {
    blocks.push(`Ключевая структура сайта:\n${SITE_MAP}`);
  }
  blocks.push(`Правила консультации:\n${ADVICE_RULES}`);
  blocks.push(`Правила техподдержки:\n${SUPPORT_RULES}`);
  return blocks.join("\n\n");
}

