function buildKnowledgeContext(userMessage) {
  const text = String(userMessage || "").toLowerCase();
  const wantsSiteHelp = /(сайт|страниц|куда|где|кнопк|нажать|перейти|раздел|меню|профил|заказ|войти|регистр|ошибк|не работ|не загруж|404|белый)/i.test(text);
  const wantsPrintHelp = /(3d|3-д|печат|напечат|хочу|нужн|сделать|чехол|детал|модел|скан|материал|pla|petg|tpu|sla|fdm|смол|прототип|фигурк|креплен|держател)/i.test(text);
  const wantsErrorHelp = /(ошибк|не работ|не могу|сломал|баг|внутренн|сервер|не загруж|не открыв)/i.test(text);

  const blocks = [SITE_PAGES, SITE_BUTTONS, SITE_GUIDE, ORDER_FLOW, SERVICE_SCENARIOS, PRODUCT_RECOMMENDATIONS];
  if (wantsErrorHelp) blocks.push(ERROR_GUIDE);
  if (wantsPrintHelp) blocks.push(PRINT_BASICS);
  blocks.push(ADVICE_RULES, SUPPORT_RULES);
  return blocks.join("\n\n");
}

